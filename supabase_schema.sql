-- ========================================================
-- Schema Oficial PoloCoin - Banco de Dados Supabase (PostgreSQL)
-- Copie e cole este código no SQL Editor do seu projeto Supabase:
-- ========================================================

-- 1. Tabela de Administradores
CREATE TABLE IF NOT EXISTS admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    password TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Insere administrador padrão se a tabela estiver vazia
INSERT INTO admins (name, password)
SELECT 'Direção Escolar', 'admin123'
WHERE NOT EXISTS (SELECT 1 FROM admins LIMIT 1);

-- 2. Tabela de Turmas Escolares
CREATE TABLE IF NOT EXISTS turmas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serie INT NOT NULL,
    turma VARCHAR(10) NOT NULL,
    ano_letivo INT NOT NULL DEFAULT 2026,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(serie, turma, ano_letivo)
);

-- 3. Tabela de Professores
CREATE TABLE IF NOT EXISTS professores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    usuario TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Tabela de Vínculo Professor x Turma
CREATE TABLE IF NOT EXISTS professor_turmas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id BIGINT REFERENCES professores(id) ON DELETE CASCADE,
    turma_id BIGINT REFERENCES turmas(id) ON DELETE CASCADE,
    UNIQUE(professor_id, turma_id)
);

-- 5. Tabela de Responsáveis Legais
CREATE TABLE IF NOT EXISTS responsaveis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    usuario TEXT UNIQUE NOT NULL,
    senha TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Tabela de Alunos / Estudantes
CREATE TABLE IF NOT EXISTS alunos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    turma_id BIGINT REFERENCES turmas(id) ON DELETE SET NULL,
    responsavel_id BIGINT REFERENCES responsaveis(id) ON DELETE SET NULL,
    avatar TEXT DEFAULT '🦊',
    pontos INT DEFAULT 0,
    pode_comprar BOOLEAN DEFAULT TRUE,
    senha TEXT DEFAULT '123',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Tabela de Categorias da Loja
CREATE TABLE IF NOT EXISTS categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT UNIQUE NOT NULL
);

-- Insere as 6 categorias padrão do catálogo se não existirem
INSERT INTO categorias (nome)
VALUES ('Alimentação'), ('Beleza'), ('Vestuário'), ('Limpeza'), ('Eletrônicos'), ('Brinquedos')
ON CONFLICT (nome) DO NOTHING;

-- 8. Tabela de Produtos / Recompensas
CREATE TABLE IF NOT EXISTS produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    custo_pontos INT NOT NULL,
    categoria TEXT NOT NULL,
    categoria_id BIGINT REFERENCES categorias(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Tabela de Avaliações Pedagógicas / Ocorrências
CREATE TABLE IF NOT EXISTS avaliacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id BIGINT REFERENCES alunos(id) ON DELETE CASCADE,
    professor_id BIGINT REFERENCES professores(id) ON DELETE SET NULL,
    professor_nome TEXT,
    categoria TEXT NOT NULL,
    valor TEXT NOT NULL,
    pontos INT NOT NULL,
    tipo VARCHAR(20) NOT NULL, -- 'positiva' ou 'negativa'
    observacao TEXT,
    data VARCHAR(20),
    hora VARCHAR(10),
    consentido BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. Tabela de Compras / Resgates na Loja
CREATE TABLE IF NOT EXISTS compras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id BIGINT REFERENCES alunos(id) ON DELETE CASCADE,
    produto_id BIGINT REFERENCES produtos(id) ON DELETE SET NULL,
    produto_nome TEXT NOT NULL,
    custo_pontos INT NOT NULL,
    categoria_nome TEXT,
    autorizado_por BIGINT REFERENCES responsaveis(id) ON DELETE SET NULL,
    entregue BOOLEAN DEFAULT FALSE,
    criado_em TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 11. Tabela de Desejos dos Estudantes
CREATE TABLE IF NOT EXISTS desejos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id BIGINT REFERENCES alunos(id) ON DELETE CASCADE,
    produto_id BIGINT REFERENCES produtos(id) ON DELETE CASCADE,
    criado_em TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(aluno_id, produto_id)
);

-- 12. Tabela de Histórico de Movimentações de Alunos (Transferências e Progressões)
CREATE TABLE IF NOT EXISTS movimentacoes_alunos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id BIGINT REFERENCES alunos(id) ON DELETE CASCADE,
    aluno_nome TEXT NOT NULL,
    aluno_matricula TEXT,
    turma_origem_id BIGINT REFERENCES turmas(id) ON DELETE SET NULL,
    turma_origem_nome TEXT NOT NULL,
    ano_letivo_origem INT NOT NULL,
    turma_destino_id BIGINT REFERENCES turmas(id) ON DELETE SET NULL,
    turma_destino_nome TEXT NOT NULL,
    ano_letivo_destino INT NOT NULL,
    tipo VARCHAR(20) NOT NULL, -- 'transferencia' ou 'progressao'
    data_hora TIMESTAMPTZ DEFAULT NOW(),
    admin_nome TEXT NOT NULL,
    lote_id TEXT NOT NULL,
    motivo TEXT,
    resultado VARCHAR(20) DEFAULT 'sucesso',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ========================================================
-- Políticas de Segurança (Row Level Security - RLS)
