ALTER TABLE turmas ENABLE ROW LEVEL SECURITY;
ALTER TABLE professores ENABLE ROW LEVEL SECURITY;
ALTER TABLE professor_turmas ENABLE ROW LEVEL SECURITY;
ALTER TABLE responsaveis ENABLE ROW LEVEL SECURITY;
ALTER TABLE alunos ENABLE ROW LEVEL SECURITY;
ALTER TABLE categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE produtos ENABLE ROW LEVEL SECURITY;
ALTER TABLE avaliacoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE compras ENABLE ROW LEVEL SECURITY;
ALTER TABLE desejos ENABLE ROW LEVEL SECURITY;
ALTER TABLE movimentacoes_alunos ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Acesso publico anon admins" ON admins FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso publico anon turmas" ON turmas FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso publico anon professores" ON professores FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso publico anon professor_turmas" ON professor_turmas FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso publico anon responsaveis" ON responsaveis FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso publico anon alunos" ON alunos FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso publico anon categorias" ON categorias FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso publico anon produtos" ON produtos FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso publico anon avaliacoes" ON avaliacoes FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso publico anon compras" ON compras FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso publico anon desejos" ON desejos FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso publico anon movimentacoes_alunos" ON movimentacoes_alunos FOR ALL USING (true) WITH CHECK (true);

