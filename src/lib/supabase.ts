import { createClient, SupabaseClient } from '@supabase/supabase-js';

const STORAGE_URL_KEY = 'polocoin_supabase_url';
const STORAGE_ANON_KEY = 'polocoin_supabase_anon_key';

export function getSupabaseConfig(): { url: string; anonKey: string; isConfigured: boolean; source: 'env' | 'storage' | 'none' } {
  const envUrl = (import.meta as any).env?.VITE_SUPABASE_URL || (import.meta as any).env?.SUPABASE_URL || '';
  const envKey = (import.meta as any).env?.VITE_SUPABASE_ANON_KEY || (import.meta as any).env?.SUPABASE_ANON_KEY || '';

  if (envUrl && envKey) {
    return { url: envUrl.trim(), anonKey: envKey.trim(), isConfigured: true, source: 'env' };
  }

  const storedUrl = localStorage.getItem(STORAGE_URL_KEY) || '';
  const storedKey = localStorage.getItem(STORAGE_ANON_KEY) || '';

  if (storedUrl && storedKey) {
    return { url: storedUrl.trim(), anonKey: storedKey.trim(), isConfigured: true, source: 'storage' };
  }

  return { url: '', anonKey: '', isConfigured: false, source: 'none' };
}

export function saveSupabaseConfig(url: string, anonKey: string) {
  if (url && anonKey) {
    localStorage.setItem(STORAGE_URL_KEY, url.trim());
    localStorage.setItem(STORAGE_ANON_KEY, anonKey.trim());
  } else {
    localStorage.removeItem(STORAGE_URL_KEY);
    localStorage.removeItem(STORAGE_ANON_KEY);
  }
}

let cachedClient: SupabaseClient | null = null;
let currentKeyHash = '';

export function getSupabaseClient(): SupabaseClient | null {
  const config = getSupabaseConfig();
  if (!config.isConfigured) {
    return null;
  }

  const hash = `${config.url}_${config.anonKey}`;
  if (cachedClient && currentKeyHash === hash) {
    return cachedClient;
  }

  try {
    cachedClient = createClient(config.url, config.anonKey, {
      auth: {
        persistSession: true,
        autoRefreshToken: true,
      },
    });
    currentKeyHash = hash;
    return cachedClient;
  } catch (err) {
    console.error('Erro ao inicializar cliente Supabase:', err);
    return null;
  }
}

export async function testSupabaseConnection(url?: string, anonKey?: string): Promise<{ success: boolean; message: string; tablesFound?: string[] }> {
  try {
    const targetUrl = url || getSupabaseConfig().url;
    const targetKey = anonKey || getSupabaseConfig().anonKey;

    if (!targetUrl || !targetKey) {
      return { success: false, message: 'URL e Anon Key do Supabase são obrigatórias.' };
    }

    const client = createClient(targetUrl, targetKey);
    // Testa consulta básica
    const { error: errTurmas } = await client.from('turmas').select('id').limit(1);

    if (errTurmas) {
      // Se der erro de tabela não existente, o cliente conectou mas as tabelas precisam ser criadas
      if (errTurmas.message.includes('relation') || errTurmas.code === '42P01') {
        return {
          success: true,
          message: 'Conectado ao Supabase com sucesso! (Por favor, execute o script SQL das tabelas no painel do Supabase).',
        };
      }
      return { success: false, message: `Erro ao comunicar com o Supabase: ${errTurmas.message}` };
    }

    return { success: true, message: 'Conexão com o Supabase estabelecida e tabelas validadas!' };
  } catch (err: any) {
    return { success: false, message: err.message || 'Falha ao testar conexão com Supabase.' };
  }
}

